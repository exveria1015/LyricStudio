/** Generate a dependency-free offline app shell after Vite has finished building. */
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, relative, sep } from 'node:path'
import { fileURLToPath, URL } from 'node:url'
import process from 'node:process'
import { log } from 'node:console'

const dist = process.argv[2] ? resolve(process.argv[2]) : fileURLToPath(new URL('../dist/', import.meta.url))
async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) files.push(...await filesIn(path))
    else if (entry.isFile()) files.push(path)
  }
  return files
}

const files = (await filesIn(dist))
  .map(path => relative(dist, path).split(sep).join('/'))
  .filter(path => path !== 'sw.js' && !path.endsWith('.map') && !path.split('/').some(part => part.startsWith('.')))
  .sort()
if (!files.includes('index.html')) throw new Error(`Build index.html before generating the offline shell: ${dist}`)
const digest = createHash('sha256')
digest.update(await readFile(fileURLToPath(import.meta.url)))
let assetBytes = 0
for (const file of files) {
  const bytes = await readFile(resolve(dist, file))
  digest.update(file).update('\0').update(bytes).update('\0')
  assetBytes += bytes.byteLength
}
const version = digest.digest('hex').slice(0, 20)
const worker = `/* Generated by scripts/build-offline.mjs; do not edit. */
'use strict';
const SCOPE = new URL(self.registration.scope);
const CACHE_PREFIX = 'lyrics-studio-offline-v1-' + encodeURIComponent(SCOPE.pathname) + '-';
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
const ASSETS = FILES.map(file => new URL(file, SCOPE).href);
const ASSET_URLS = new Set(ASSETS);
const SHELL = new URL('index.html', SCOPE).href;

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Installation succeeds only when the entire version is available offline.
    try {
      await cache.addAll(ASSETS.map(url => new Request(url, { cache: 'reload' })));
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) return response;
        const shell = await (await caches.open(CACHE_NAME)).match(SHELL);
        return shell || response;
      } catch (error) {
        const shell = await (await caches.open(CACHE_NAME)).match(SHELL);
        if (shell) return shell;
        throw error;
      }
    })());
    return;
  }
  // Cache only the versioned app's known static resources, never user documents.
  if (ASSET_URLS.has(url.href)) {
    // Use the same canonical GET as precaching. Module requests can carry an
    // Origin header (Vary: Origin) that the installation's GET did not carry.
    event.respondWith((async () => (await (await caches.open(CACHE_NAME)).match(url.href)) || fetch(request))());
  }
});
`
await writeFile(resolve(dist, 'sw.js'), worker)
log(`Offline shell ${version}: ${files.length} files, ${assetBytes.toLocaleString('en-US')} bytes precached.`)
