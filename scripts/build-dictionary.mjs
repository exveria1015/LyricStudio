/** Rebuild the complete, pinned CMUdict syllable index with Node's standard library. */
import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { gzipSync } from 'node:zlib'
import { URL } from 'node:url'
import { Buffer } from 'node:buffer'
import process from 'node:process'
import { log } from 'node:console'

const commit = '74790861f652b15e4ac49015a90074ad62a27690'
const origin = `https://raw.githubusercontent.com/cmusphinx/cmudict/${commit}`
const root = new URL('../', import.meta.url)
async function source(name, local) {
  if (local) return readFile(local, 'utf8')
  const response = await globalThis.fetch(`${origin}/${name}`)
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`)
  return response.text()
}
const dictionary = await source('cmudict.dict', process.argv[2])
const license = await source('LICENSE', process.argv[3])
const words = new Map()
let pronunciations = 0
for (const line of dictionary.split(/\r?\n/u)) {
  if (!line || line.startsWith(';;;')) continue
  const [rawWord, ...phones] = line.split(' #')[0].trim().split(/\s+/u)
  const word = rawWord.replace(/\(\d+\)$/u, '')
  const syllables = phones.filter(phone => /[012]$/u.test(phone)).length
  const existing = words.get(word) ?? new Set()
  existing.add(syllables)
  words.set(word, existing)
  pronunciations++
}
const entries = [...words].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
// Preserve every distinct syllable count, including alternative pronunciations.
const data = entries.map(([word, counts]) => `${word}\t${[...counts].sort((a, b) => a - b).join(',')}`).join('\n')
const moduleText = `// Generated by scripts/build-dictionary.mjs. CMUdict license: /dictionary/LICENSE\nexport const CMUDICT_DATA = ${JSON.stringify(data)}\n`
await mkdir(new URL('src/analysis/', root), { recursive: true })
await mkdir(new URL('public/dictionary/', root), { recursive: true })
await writeFile(new URL('src/analysis/cmudict-data.ts', root), moduleText)
await writeFile(new URL('public/dictionary/LICENSE', root), license)
const provenance = {
  name: 'CMU Pronouncing Dictionary', source: 'https://github.com/cmusphinx/cmudict', commit,
  sourceUrl: `${origin}/cmudict.dict`, licenseUrl: `${origin}/LICENSE`,
  sourceSha256: createHash('sha256').update(dictionary).digest('hex'),
  dictionaryVersion: 'cmudict-74790861',
  pronunciations, words: words.size,
  ambiguousWords: entries.filter(([, counts]) => counts.size > 1).length,
  sourceBytes: Buffer.byteLength(dictionary), syllableIndexBytes: Buffer.byteLength(data),
  syllableIndexGzipBytes: gzipSync(data).length,
  transformation: 'All headwords retained; numbered pronunciation variants merged; distinct counts of ARPABET vowels carrying stress 0, 1, or 2 retained in ascending order. No spelling-based estimates.',
}
await writeFile(new URL('public/dictionary/provenance.json', root), `${JSON.stringify(provenance, null, 2)}\n`)
log(JSON.stringify(provenance, null, 2))
